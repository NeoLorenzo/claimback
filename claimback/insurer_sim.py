"""Scripted stand-in for the insurer, for tests and the recorded demo. Sends
real email to a case's reply address. Every message is marked as simulated in
a header and in its first line."""
import os
import secrets
from datetime import datetime, timedelta

from .cases import Case
from .connectors import OutboundEmail, get_connector
from .log import emit
from .state import RunState

BANNER = "SIMULATED INSURER MESSAGE: generated by ClaimBack's test harness, not sent by a real insurer.\n\n"


def _scene(name: str, case: Case, patient: str, ref: str) -> tuple[str, str]:
    today = datetime.now()
    d = lambda days: (today + timedelta(days=days)).strftime("%B %d, %Y")
    head = (f"{case.insurer_name} - Appeals and Grievances\n{today:%B %d, %Y}\n\n"
            f"Member: {patient}\nRequest number: {case.claim_number}\nAppeal reference: {ref}\n\n")
    scenes = {
        "ack": (f"Appeal received - {case.claim_number}",
                f"Dear {patient},\n\nWe received your request for an internal appeal on {today:%B %d, %Y}. "
                f"Your appeal reference is {ref}. A physician reviewer will evaluate it, and we will send you a "
                f"written decision within 30 calendar days of receipt.\n\nThis letter confirms receipt only. "
                f"It is not a decision on your appeal."),
        "evidence-request": (f"Additional information needed - {case.claim_number}",
                f"Dear {patient},\n\nTo complete our review of appeal {ref}, we need the following:\n\n"
                f"1. A letter of medical necessity from the treating endocrinologist explaining why a continuous "
                f"glucose monitor is required.\n2. Glucose meter readings or downloads for the hypoglycemic "
                f"episodes described in the appeal.\n\nPlease send these within 14 calendar days of the date of "
                f"this letter (by {d(14)}). If we do not receive them, we will decide the appeal using the "
                f"information we already have."),
        "overturned": (f"Appeal decision - {case.claim_number}",
                f"Dear {patient},\n\nWe have completed our review of appeal {ref}. Our physician reviewer "
                f"found that the request meets Medical Policy MP-DME-031 as revised on 01/01/2026.\n\n"
                f"Decision: the original denial is OVERTURNED. The continuous glucose monitor system and sensors "
                f"are approved. Authorization number: AUTH-{secrets.token_hex(3).upper()}, valid for 12 months "
                f"from {today:%B %d, %Y}."),
        "upheld": (f"Appeal decision - {case.claim_number}",
                f"Dear {patient},\n\nWe have completed our review of appeal {ref}. Decision: the original denial "
                f"is UPHELD. The reviewer found that the submitted records do not meet criterion I.B of Medical "
                f"Policy MP-DME-031. This is our final internal decision.\n\nYou may request, free of charge, "
                f"copies of all documents and the clinical criteria used in this decision.\n\nYou may request an "
                f"independent external review through the state insurance regulator within four months of "
                f"receiving this letter (by about {d(120)}). An expedited external review is available if a delay "
                f"could seriously jeopardize your health. For help, contact your state insurance department's "
                f"consumer assistance office."),
    }
    if name not in scenes:
        raise SystemExit(f"unknown scene '{name}'. Choose from: {', '.join(scenes)}")
    subject, body = scenes[name]
    return subject, BANNER + head + body + f"\n\nSincerely,\nAppeals and Grievances\n{case.insurer_name}\n"


def send_scene(case_id: str, scene: str, direct: bool = False) -> str:
    """Send a scripted insurer email. direct=True skips the mailbox round trip and files the
    same message straight into the case (for a fast demo); it is still redacted and read by
    the Correspondence agent like any other mail."""
    case = Case.load(case_id)
    display = RunState.load(case.run_id).read_private("phi_map.json")["display"]
    patient = next((v for k, v in display.items() if k.startswith("[PATIENT_NAME")), "Member")
    ref = f"APL-{case.case_id[-4:].upper()}"
    subject, body = _scene(scene, case, patient, ref)

    sim_addr, sim_pw = os.environ.get("INSURER_SIM_EMAIL"), os.environ.get("INSURER_SIM_APP_PASSWORD")
    connector = get_connector()
    if connector.name == "imap" and sim_addr and sim_pw:
        from .connectors.email_imap import IMAPConnector
        connector, sender = IMAPConnector(sim_addr.strip(), sim_pw.replace(" ", "")), sim_addr.strip()
    elif connector.name == "imap":
        sender = connector.address  # no second account: send from the ClaimBack inbox, still marked simulated
    else:
        sender = case.insurer_addresses[0]
    last_out = next((c for c in reversed(case.correspondence) if c["direction"] == "out"), None)
    mail = OutboundEmail(
        from_addr=f"{case.insurer_name} Appeals (SIMULATED) <{sender}>", to=case.reply_address,
        subject=("Re: " if last_out else "") + subject, body=body, simulated=True,
        in_reply_to=last_out["message_id"] if last_out else None,
    )
    if direct:
        from .connectors.base import parse
        from .worker import record_inbound
        msg = mail.to_message()
        record_inbound(case, parse(bytes(msg)))
        emit("insurer_sim", "info", f"delivered simulated '{scene}' email straight to case {case.case_id}")
        return msg["Message-ID"]
    message_id = connector.send(mail)
    emit("insurer_sim", "info", f"sent simulated '{scene}' email to {case.reply_address} via {connector.name}")
    return message_id
